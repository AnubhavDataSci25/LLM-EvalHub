import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// The frontend never holds provider credentials: every model call is proxied
// through the FastAPI backend, which owns the keys.
export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    proxy: {
      '/api': {
        target: process.env.VITE_PROXY_TARGET || 'http://localhost:8000',
        changeOrigin: true,
      },
    },
  },
  build: {
    outDir: 'dist',
    sourcemap: false,
    chunkSizeWarningLimit: 700,
    rollupOptions: {
      output: {
        // Charts and animation are large and rarely change; splitting them keeps
        // the application chunk small enough to re-download cheaply on deploy.
        manualChunks: {
          react: ['react', 'react-dom', 'react-router-dom'],
          charts: ['recharts'],
          motion: ['framer-motion'],
        },
      },
    },
  },
})
